def t(key: str, lang: str = "bn") -> str:
    """Translate a UI string key.

    Falls back to English, then to the key itself when untranslated.
    """
    code = (lang or "bn").strip().lower()
    table = LANG.get(code, LANG["bn"])
    if key in table:
        return table[key]
    if key in LANG["en"]:
        return LANG["en"][key]
    return key
